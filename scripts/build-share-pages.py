"""Build direct entry pages from the shared app shell and per-route metadata.

Run after changing index.html or share-pages.json. --check verifies committed
output without modifying files. Generated pages never redirect or reload.
"""
from pathlib import Path
import argparse
import html
import json
import re

ROOT = Path(__file__).resolve().parents[1]


def replace_once(source, pattern, replacement):
    result, count = re.subn(pattern, lambda _: replacement, source, count=0)
    if count != 1:
        raise ValueError(f'Expected one match for {pattern!r}, found {count}')
    return result


def render_entry(template, page):
    title = html.escape(page['title'], quote=True)
    description = html.escape(page['description'], quote=True)
    url = 'https://familydaystay.com' + page['path']
    source = template.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n'
        '<!-- Generated by scripts/build-share-pages.py; edit index.html and share-pages.json. -->', 1)
    source = replace_once(source, r'<title>[^<]*</title>', f'<title>{title}</title>')
    source = replace_once(source, r'<link rel="canonical" href="[^"]*">',
                          f'<link rel="canonical" href="{url}">')
    metadata = {
        ('name', 'description'): description,
        ('property', 'og:url'): url,
        ('property', 'og:title'): title,
        ('property', 'og:description'): description,
        ('name', 'twitter:card'): 'summary',
        ('name', 'twitter:title'): title,
        ('name', 'twitter:description'): description,
    }
    for (attribute, name), value in metadata.items():
        source = replace_once(source,
            rf'<meta {attribute}="{re.escape(name)}" content="[^"]*">',
            f'<meta {attribute}="{name}" content="{value}">')
    # Keep the approved text-only previews for these links.
    source = re.sub(r'<meta (?:property="og:image(?::[^"]*)?"|name="twitter:image") content="[^"]*">\n?', '', source)
    return source


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    pages = json.loads((ROOT / 'share-pages.json').read_text())
    assert len({p['route'] for p in pages}) == len(pages)
    assert len({p['path'] for p in pages}) == len(pages)
    template = (ROOT / 'index.html').read_text()
    assert '<base href="/">' in template, 'Nested entry pages require root-relative assets'
    outputs = {ROOT / 'share-pages.js':
        '// Generated by scripts/build-share-pages.py from share-pages.json.\n'
        + 'window.FD_SHARE_PAGES = ' + json.dumps(pages, ensure_ascii=False, indent=2) + ';\n'}
    for page in pages:
        if page['entry']:
            outputs[ROOT / page['path'].strip('/') / 'index.html'] = render_entry(template, page)
    stale = []
    for path, contents in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != contents:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(contents)
    if stale:
        parser.exit(1, 'Regenerate with python3 scripts/build-share-pages.py:\n' + '\n'.join(stale) + '\n')
    print(f'{"Verified" if args.check else "Built"} {len(pages)} routes and {len(outputs)-1} direct entry pages.')


if __name__ == '__main__':
    main()
