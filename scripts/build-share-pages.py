"""Build direct entry pages and consistent text-only link previews.

Edit index.html, share-pages.json (app routes), or share-extras.json (standalone
pages). --check verifies generated output without modifying files.
"""
from pathlib import Path
import argparse
import difflib
import html
import json
import re

ROOT = Path(__file__).resolve().parents[1]


def replace_once(source, pattern, replacement):
    result, count = re.subn(pattern, lambda _: replacement, source)
    if count != 1:
        raise ValueError(f'Expected one match for {pattern!r}, found {count}')
    return result


def meta(source, attribute, name, value):
    pattern = rf'<meta\s+{attribute}="{re.escape(name)}"\s+content="[^"]*"\s*/?>'
    tag = f'<meta {attribute}="{name}" content="{html.escape(value, quote=True)}">'
    if re.search(pattern, source):
        return replace_once(source, pattern, tag)
    return source.replace('</head>', tag + '\n</head>', 1)


def render_metadata(source, page):
    title = html.escape(page['title'], quote=True)
    url = 'https://familydaystay.com' + page['path']
    source = replace_once(source, r'<title>[^<]*</title>', f'<title>{title}</title>')
    canonical = f'<link rel="canonical" href="{url}">'
    if re.search(r'<link rel="canonical" href="[^"]*">', source):
        source = replace_once(source, r'<link rel="canonical" href="[^"]*">', canonical)
    else:
        source = source.replace('</head>', canonical + '\n</head>', 1)
    for attribute, name, value in [
        ('name', 'description', page['description']),
        ('property', 'og:type', 'website'),
        ('property', 'og:url', url),
        ('property', 'og:title', page['title']),
        ('property', 'og:description', page['description']),
        ('name', 'twitter:card', 'summary'),
        ('name', 'twitter:title', page['title']),
        ('name', 'twitter:description', page['description']),
    ]:
        source = meta(source, attribute, name, value)
    source = re.sub(r'<meta\s+(?:property="og:image(?::[^"]*)?"|name="(?:twitter:image(?::[^"]*)?|thumbnail)")\s+content="[^"]*"\s*/?>\n?', '', source)
    robots = re.search(r'<meta name="robots" content="([^"]*)">', source)
    directives = [v.strip() for v in robots[1].split(',')] if robots else []
    directives = [v for v in directives if not v.startswith('max-image-preview:')]
    directives.append('max-image-preview:none')
    return meta(source, 'name', 'robots', ','.join(directives))


def render_entry(template, page, venues):
    # Only the root selector needs all three destination photos immediately.
    # Deep links retain their own media priorities and unchanged photo sources.
    template = re.sub(r'<!-- Warm the visible destination photos[^\n]*-->\n?', '', template)
    template = re.sub(r'<link data-destination-preload[^>]*>\n?', '', template)
    source = template.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n'
        '<!-- Generated by scripts/build-share-pages.py; edit index.html and share-pages.json. -->', 1)
    source = render_metadata(source, page)
    venue = 'stay' if page['path'].startswith('/stay/') else 'chalet' if page['path'].startswith('/chalet/') else 'resort'
    return replace_once(source, r'<script id="fd-venue-schema" type="application/ld\+json">[\s\S]*?</script>',
                        '<script id="fd-venue-schema" type="application/ld+json">\n' + json.dumps(venues[venue], ensure_ascii=False, indent=2) + '\n</script>')


def write_preserving_endings(path, contents):
    """Standalone sources have mixed historical line endings; keep unchanged lines."""
    if path.exists() and b'\r\n' in path.read_bytes():
        old = path.read_bytes().decode().splitlines(keepends=True)
        before = [line.rstrip('\r\n') for line in old]
        after = contents.splitlines()
        lines = [line + '\r\n' for line in after]
        for block in difflib.SequenceMatcher(None, before, after, autojunk=False).get_matching_blocks():
            for offset in range(block.size):
                lines[block.b + offset] = old[block.a + offset]
        path.write_bytes(''.join(lines).encode())
    else:
        path.write_text(contents)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    pages = json.loads((ROOT / 'share-pages.json').read_text())
    extras = json.loads((ROOT / 'share-extras.json').read_text())
    venues = json.loads((ROOT / 'venue-data.json').read_text())
    assert len({p['route'] for p in pages}) == len(pages)
    assert len({p['path'] for p in pages + extras}) == len(pages + extras)
    home = next(p for p in extras if p['path'] == '/')
    template = render_metadata((ROOT / 'index.html').read_text(), home)
    assert '<base href="/">' in template, 'Nested entry pages require root-relative assets'
    outputs = {
        ROOT / 'index.html': template,
        ROOT / 'share-pages.js': '// Generated by scripts/build-share-pages.py.\n'
        + 'window.FD_SHARE_PAGES = ' + json.dumps(pages, ensure_ascii=False, indent=2) + ';\n'
        + 'window.FD_SHARE_ROOT = ' + json.dumps(home, ensure_ascii=False, indent=2) + ';\n',
        ROOT / 'venue-data.js': '// Generated from venue-data.json by scripts/build-share-pages.py.\nwindow.FD_VENUE_SCHEMAS = '
        + json.dumps(venues, ensure_ascii=False, indent=2) + ';\n'
    }
    for page in pages + extras:
        if page['path'] == '/':
            continue
        path = ROOT / page['path'].strip('/') / 'index.html'
        outputs[path] = render_entry(template, page, venues) if page.get('entry') else render_metadata(path.read_text(), page)
    # Legacy alias keeps the same preview as the canonical guest link.
    outputs[ROOT / 'guest-services.html'] = render_metadata((ROOT / 'guest-services.html').read_text(), next(p for p in extras if p['path'] == '/guest-services/'))
    stale = []
    for path, contents in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != contents:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            write_preserving_endings(path, contents)
    if stale:
        parser.exit(1, 'Regenerate with python3 scripts/build-share-pages.py:\n' + '\n'.join(stale) + '\n')
    print(f'{"Verified" if args.check else "Built"} {len(pages)} routes, {sum(bool(p["entry"]) for p in pages)} direct entry pages and {len(extras)} standalone previews.')


if __name__ == '__main__':
    main()
